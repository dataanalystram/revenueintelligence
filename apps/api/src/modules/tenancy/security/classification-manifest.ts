/** One table's link to data subjects (plan §14): which columns, which entity, which intended action. */
export interface DataSubjectLink {
  readonly table: string;
  readonly columns: readonly {
    readonly column: string;
    readonly entity: 'person' | 'company';
    readonly action: 'export' | 'erase' | 'pseudonymise' | 'retain';
  }[];
  /** True when the table holds a `personal` column. */
  readonly personal: boolean;
}

/**
 * The data-subject map, derived from the manifest: hooks for future export and
 * erasure (control 17). No export or erasure feature exists in M10A1.
 */
export function dataSubjectMap(
  manifest: typeof CLASSIFICATION_MANIFEST = CLASSIFICATION_MANIFEST,
): DataSubjectLink[] {
  return Object.entries(manifest)
    .map(([table, columns]) => ({
      table,
      columns: Object.entries(columns).flatMap(([column, c]) =>
        c.subject ? [{ column, entity: c.subject.entity, action: c.subject.action }] : [],
      ),
      personal: Object.values(columns).some((c) => c.categories.includes('personal')),
    }))
    .filter((t) => t.columns.length > 0 || t.personal);
}
