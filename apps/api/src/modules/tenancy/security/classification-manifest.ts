import type { ColumnClassification } from '../../domain';

/**
 * Classification manifest (M10A1 plan §9, owner decision Q6): one entry per
 * column of every table except `_prisma_migrations`. The schema guard
 * (test/tenancy/migrations.int.spec.ts) fails when a column has no entry, an
 * entry names no column, a floor is broken, or a `tbc` entry lacks a reason
 * and an owner. A `tbc` entry is treated operationally as `restricted`.
 *
 * `kind` decides where secret detection applies (plan §11: `free_text` and
 * `json`). `subject` feeds the data-subject map (plan §14). Retention classes
 * are product defaults, not compliance claims.
 */

